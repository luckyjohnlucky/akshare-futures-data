class ConsistencyIntegrationTests(unittest.TestCase):
    """Integration tests for pre-flight consistency check + rebuild flow."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.dir = Path(self.tmp.name)
        self._orig = {
            "MINUTE_BARS": m.MINUTE_BARS,
            "MINUTE_BARS_CSV": m.MINUTE_BARS_CSV,
            "DAILY_BARS": m.DAILY_BARS,
            "DAILY_BARS_CSV": m.DAILY_BARS_CSV,
            "OUT": m.OUT,
        }

    def tearDown(self):
        for attr, path in self._orig.items():
            setattr(m, attr, path)
        self.tmp.cleanup()

    def _setup_temp_paths(self):
        """Redirect all output paths to isolated temp directory."""
        m.OUT = self.dir
        m.MINUTE_BARS = self.dir / "minute_bars.json"
        m.MINUTE_BARS_CSV = self.dir / "minute_bars.csv"
        m.DAILY_BARS = self.dir / "daily_bars.json"
        m.DAILY_BARS_CSV = self.dir / "daily_bars.csv"

    def test_normal_consistency_both_paths(self):
        """T5/T6: After normal json_to_csv, both minute and daily paths are consistent."""
        self._setup_temp_paths()

        # Minute path
        m.MINUTE_BARS.write_text(json.dumps(SAMPLE_RECORDS), encoding="utf-8")
        m.json_to_csv(m.MINUTE_BARS, m.MINUTE_BARS_CSV)
        self.assertTrue(m.json_matches_csv(m.MINUTE_BARS, m.MINUTE_BARS_CSV))

        # Daily path
        m.DAILY_BARS.write_text(json.dumps(SAMPLE_RECORDS), encoding="utf-8")
        m.json_to_csv(m.DAILY_BARS, m.DAILY_BARS_CSV)
        self.assertTrue(m.json_matches_csv(m.DAILY_BARS, m.DAILY_BARS_CSV))

    def test_preflight_rebuilds_inconsistent_csv(self):
        """Pre-flight detects inconsistency and rebuilds CSV."""
        self._setup_temp_paths()

        m.MINUTE_BARS.write_text(json.dumps(SAMPLE_RECORDS), encoding="utf-8")
        m.MINUTE_BARS_CSV.write_text("stale\n", encoding="utf-8")

        self.assertFalse(m.json_matches_csv(m.MINUTE_BARS, m.MINUTE_BARS_CSV))

        # Simulate the pre-flight logic from __main__
        for json_file, csv_file, label in [
            (m.MINUTE_BARS, m.MINUTE_BARS_CSV, "minute"),
        ]:
            if json_file.exists() and (
                not csv_file.exists() or not m.json_matches_csv(json_file, csv_file)
            ):
                m.json_to_csv(json_file, csv_file)

