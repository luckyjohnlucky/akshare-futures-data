#!/usr/bin/env python3
"""Tests for JSON-authoritative CSV consistency and rebuild semantics.

Covers:
- Normal JSON/CSV consistency (minute + daily path)
- Value mismatch detection
- Record order mismatch detection
- Record count mismatch detection
- JSON null ↔ CSV empty string mapping
- CSV row missing fields
- CSV row extra fields
- CSV duplicate header fields
- JSON field set vs CSV header mismatch
- JSON non-dict items
- Empty JSON with valid empty CSV
- Empty JSON with no-header CSV
- Missing JSON or CSV file
- Corrupted JSON format
- CSV rebuild failure preserves JSON
- CSV can be rebuilt from JSON after failure

All tests use temp directories; no real output files are touched.
"""

